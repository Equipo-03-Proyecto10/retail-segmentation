#!/usr/bin/env python3
"""Generate the local gateway's NGINX configuration from the registry (F13-08).

    python3 docker/distributed/gateway/generate.py           # rewrite it
    python3 docker/distributed/gateway/generate.py --check   # exit 1 if stale

One `location /api/<name>/` per entry of contracts/registry.yaml, rendered from
the instance's own template (deploy/templates/service/nginx.conf), so both
clients and the negative suite see the same prefixes, body limit, forwarded
headers and 413 envelope locally as on the instance. Only the upstream
differs: the service's container on the `mosaiq` network, resolved per request
through Docker's DNS, so the gateway starts while a service is down and only
that prefix answers 502. This file and its output never reach the instance.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
OUTPUT = Path(__file__).resolve().parent / "default.conf"

_spec = importlib.util.spec_from_file_location(
    "service_template", ROOT / "deploy/templates/service/render.py"
)
_template = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_template)

HEADER = """\
# GENERATED by docker/distributed/gateway/generate.py from
# contracts/registry.yaml. Do not edit; run the generator. Local only: the
# instance's includes come from services/<name>/nginx/<name>.conf.

# The maps of deploy/nginx/mosaiq.conf that the includes use.
map $http_accept $mosaiq_error_format {
    default json;
    ~application/xml xml;
}

map $http_x_correlation_id $mosaiq_correlation_id {
    default $request_id;
    "~^[0-9A-Za-z-]{1,64}$" $http_x_correlation_id;
}

map $uri $mosaiq_script_sources {
    default "'self'";
}

server {
    listen 8080;
    server_tokens off;
    # Docker's embedded DNS, asked per request, so an absent service is a 502
    # on its own prefix and never stops the gateway from starting.
    resolver 127.0.0.11 valid=10s ipv6=off;
"""


def upstream_variable(name: str) -> str:
    return "$mosaiq_upstream_" + name.replace("-", "_")


def location(name: str, port: int) -> str:
    instance = f"    proxy_pass http://127.0.0.1:{port}/;\n"
    rendered = _template.render_nginx(name, port, auth=False)
    if rendered.count(instance) != 1:
        raise ValueError(f"{name}: the template's proxy_pass line changed")
    variable = upstream_variable(name)
    local = (
        f"    set {variable} {name}:{port};\n"
        f"    rewrite ^/api/{name}/(.*)$ /$1 break;\n"
        f"    proxy_pass http://{variable};\n"
    )
    # The template's comments describe the instance; the header covers these.
    body = rendered[rendered.index("location /api/") :].replace(instance, local)
    lines = [line for line in body.splitlines() if not line.lstrip().startswith("#")]
    compact: list[str] = []
    for line in lines:
        if line.strip() == "}" and compact and not compact[-1]:
            compact.pop()
        if line or (compact and compact[-1]):
            compact.append(line)
    return "\n".join(compact).strip() + "\n"


def generate() -> str:
    registry = yaml.safe_load((ROOT / "contracts/registry.yaml").read_text())
    blocks = [
        location(entry["name"], int(entry["port"])) for entry in registry["services"]
    ]
    indented = "\n".join(
        "\n".join(("    " + line) if line else line for line in block.splitlines())
        for block in blocks
    )
    return HEADER + "\n" + indented + "\n}\n"


def main(argv: list[str]) -> int:
    text = generate()
    if argv == ["--check"]:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale: run {Path(__file__).name}")
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
