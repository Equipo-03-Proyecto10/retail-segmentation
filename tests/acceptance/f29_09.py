def _median(values: list[int]) -> str:
    if not values:
        return "—"
    m = statistics.median(values)
    return str(int(m)) if float(m).is_integer() else f"{m:.1f}"


def _mean(values: list[float]) -> str:
    return "—" if not values else f"{statistics.fmean(values):.1f}"


def _score(value: float | None) -> str:
    if value is None:
        return "not asked (stopped)"
    return f"{value:.1f}" if not math.isclose(value, round(value)) else f"{value:.0f}"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines


def _issue(number: int | None) -> str:
    return "—" if number is None else f"#{number}"


def render_coverage(results: Results) -> list[str]:
    rows = []
    for role, (client, label, _) in ROLES.items():
        mine = [s for s in results.sessions if s.role == role]
        real = sorted(s.participant for s in mine if s.standing == "real")
        stand = sorted(s.participant for s in mine if s.standing == "stand-in")
        if real:
            verdict = "tested by someone who does the work"
        elif stand:
            verdict = "**stand-ins only**: not tested by someone who does the work"
        else:
            verdict = "**not tested**"
        rows.append(
            [
                f"{label} (`{role}`)",
                client.capitalize(),
                TARGETS[role],
                ", ".join(real) or "—",
                ", ".join(stand) or "—",
                verdict,
            ]
        )
    return _table(["Role", "Client", "Target", "Real", "Stand-in", "Verdict"], rows)


def render_participants(results: Results) -> list[str]:
    if not results.sessions:
        return ["No session has been recorded yet."]
    rows = []
    for s in sorted(results.sessions, key=lambda s: (int(s.participant[2:]), s.client)):
        rows.append(
            [
                s.participant,
                s.client.capitalize(),
                ROLES[s.role][1],
                s.standing,
                s.when.isoformat(),
                "stopped" if s.stopped else "finished",
                "yes" if s.recording else "no",
                _score(s.score),
            ]
        )
    return _table(
        [
            "Participant",
            "Client",
            "Role",
            "Standing",
            "Date",
            "Session",
            "Recorded",
            "SUS",
        ],
        rows,
    )


def render_tasks(results: Results, standing: str) -> list[str]:
    sessions = [s for s in results.sessions if s.standing == standing]
    if not sessions:
        return [f"No {standing} participant has been recorded."]
    rows = []
    for client in CLIENTS:
        order: list[str] = []
        for c, _, tasks in ROLES.values():
            if c == client:
                order += tasks
        if client == "android":
            order += CONNECTION_TASKS
        for task in order:
            done = [s.tasks[task] for s in sessions if task in s.tasks]
            if not done:
                continue
            counts = {o: sum(t.outcome == o for t in done) for o in OUTCOMES}
            rows.append(
                [
                    task,
                    str(len(done)),
                    f"{counts['complete']} of {len(done)}",
                    str(counts["assisted"]),
                    str(counts["failed"]),
                    _median([t.seconds for t in done]),
                    _median([t.errors for t in done]),
                    str(sum(t.errors for t in done)),
                ]
            )
    return _table(
        [
            "Task",
            "n",
            "Complete unaided",
            "Assisted",
            "Failed",
            "Median s",
            "Median errors",
            "Total errors",
        ],
        rows,
    )


def render_sus(results: Results) -> list[str]:
    rows = []
    for client in CLIENTS:
        scored = [s for s in results.sessions if s.client == client and s.sus]
        each = ", ".join(
            f"{s.participant} {_score(s.score)}"
            + (" (stand-in)" if s.standing == "stand-in" else "")
            for s in scored
        )
        rows.append(
            [
                client.capitalize(),
                str(len(scored)),
                each or "—",
                _mean([s.score for s in scored if s.score is not None]),
                _mean(
                    [
                        s.score
                        for s in scored
                        if s.standing == "real" and s.score is not None
                    ]
                ),
            ]
        )
    return _table(
        ["Client", "n", "Each score", "Mean, everyone", "Mean, real only"], rows
    )


def render_metrics(results: Results) -> list[str]:
    rows = []
    for client in CLIENTS:
        for m in METRICS:
            readings = [
                s.metrics[m]
                for s in results.sessions
                if s.client == client and m in s.metrics
            ]
            if not readings:
                continue
            rows.append(
                [client.capitalize(), m] + [str(readings.count(r)) for r in READINGS]
            )
    if not rows:
        return ["No metric reading has been recorded yet."]
    return _table(["Client", "Question", *READINGS], rows)


def render_findings(results: Results) -> list[str]:
    if not results.findings:
        return ["No finding has been recorded yet."]
    order = {s: i for i, s in enumerate(SEVERITIES)}
    rows = []
    for f in sorted(results.findings, key=lambda f: (order[f.severity], f.id)):
        if f.outcome == "fixed":
            outcome = f"fixed in #{f.fixed_by}" if f.fixed_by else "fixed"
        elif f.outcome == "not-fixing":
            outcome = f"not fixing: {f.reason}"
        else:
            outcome = "open"
        rows.append(
            [
                f.id,
                f.severity,
                f.client.capitalize(),
                ", ".join(f.tasks),
                ", ".join(f.seen_by),
                f.summary,
                _issue(f.issue),
                outcome,
            ]
        )
    return _table(
        ["Id", "Severity", "Client", "Tasks", "Seen by", "Finding", "Issue", "Outcome"],
        rows,
    )


def render_quotes(results: Results, attribute: str, client: str | None) -> list[str]:
    lines = []
    for s in results.sessions:
        if client and s.client != client:
            continue
        quote = getattr(s, attribute)
        if quote:
            who = f"{s.participant}, {ROLES[s.role][1].lower()}, {s.standing}"
            lines.append(f"- {who}: “{quote}”")
    return lines or ["None recorded yet."]


def render(results: Results) -> str:
    """The generated half of the report, from the records alone."""
    parts = [
        ("Coverage of the roles", render_coverage(results)),
        ("Participants", render_participants(results)),
        (
            "Results per task, real participants",
            render_tasks(results, "real"),
        ),
        (
            "Results per task, stand-ins (not evidence of a real role's experience)",
            render_tasks(results, "stand-in"),
        ),
        ("SUS per client", render_sus(results)),
        ("Metric readings", render_metrics(results)),
        ("Findings", render_findings(results)),
        (
            "What was hardest, in the participants' words",
            render_quotes(results, "hardest", None),
        ),
        (
            "What the desktop gave them that the web does not, in their words",
            render_quotes(results, "desktop_over_web", "desktop"),
        ),
    ]
    out: list[str] = []
    for title, lines in parts:
        out += [f"#### {title}", "", *lines, ""]
    return "\n".join(out).rstrip() + "\n"


def generated_block(report: str) -> str:
    try:
        start = report.index(BEGIN) + len(BEGIN)
        end = report.index(END, start)
    except ValueError:
        raise RecordError(
            f"{REPORT.name} has lost its generated-block markers"
        ) from None
    return report[start:end].strip("\n") + "\n"


def write_block(report: str, block: str) -> str:
    start = report.index(BEGIN) + len(BEGIN)
    end = report.index(END, start)
    return report[:start] + "\n\n" + block + "\n" + report[end:]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m tests.acceptance.f29_09")
    commands = parser.add_subparsers(dest="command", required=True)
    check = commands.add_parser("check", help="validate the session records")
    check.add_argument("--final", action="store_true")
    show = commands.add_parser("render", help="render the generated results")
    show.add_argument("--write", action="store_true")
    parser.add_argument("--dir", type=Path, default=EVIDENCE, help=argparse.SUPPRESS)
    parser.add_argument("--report", type=Path, default=REPORT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    try:
        results = load(args.dir)
    except RecordError as error:
        print(f"refused: {error}", file=sys.stderr)
        return 1

    if args.command == "render":
        block = render(results)
        if args.write:
            report = args.report.read_text(encoding="utf-8")
            args.report.write_text(write_block(report, block), encoding="utf-8")
            print(f"wrote the generated block of {args.report.name}")
        else:
            print(block, end="")
        return 0

    sessions = len(results.sessions)
    print(f"{sessions} session(s) and {len(results.findings)} finding(s) are valid")
    if args.final:
        problems = final_problems(results, args.report.read_text(encoding="utf-8"))
        for problem in problems:
            print(f"not final: {problem}", file=sys.stderr)
        return 1 if problems else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
